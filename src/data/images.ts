/**
 * Helper to resolve an image key or category ID to a valid image URL from Images.
 */
export function getImageUrlByKey(keyOrCategory?: string): string {
  if (!keyOrCategory) return Images.defaultFood;
  if (keyOrCategory in Images) {
    return (Images as Record<string, any>)[keyOrCategory];
  }
  if (keyOrCategory in Images.categories) {
    return (Images.categories as Record<string, string>)[keyOrCategory];
  }
  const categoryMap: Record<string, string> = {
    'crepes-mix': Images.categories.crepesMix,
    'sandwiches-french': Images.categories.sandwichesFrench,
    'fried-chicken': Images.categories.friedChicken,
    'burgers': Images.categories.burgers,
    'waffles': Images.categories.waffles,
    'sweet-crepes': Images.categories.sweetCrepes,
    'pancakes': Images.categories.pancakes,
    'donuts': Images.categories.donuts,
    'oriental-sweets': Images.categories.orientalSweets,
    'western-cakes': Images.categories.westernCakes,
    'eid-kahk': Images.categories.kahkEid,
    'kahk-el-eid': Images.categories.kahkEid,
    'koshary-kashtouta': Images.categories.kosharyKashtouta,
    'cold-drinks': Images.categories.coldDrinks,
    'hot-drinks': Images.categories.hotDrinks,
  };
  return categoryMap[keyOrCategory] || Images.defaultFood;
}
